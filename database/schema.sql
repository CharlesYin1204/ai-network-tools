CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('user','admin') NOT NULL DEFAULT 'user', status ENUM('active','disabled') NOT NULL DEFAULT 'active',
 avatar VARCHAR(500) DEFAULT '', bio TEXT, company VARCHAR(160) DEFAULT '', city VARCHAR(100) DEFAULT '', industry VARCHAR(100) DEFAULT '', title VARCHAR(120) DEFAULT '', skills JSON,
 visibility ENUM('public','contacts','second_degree','hidden') DEFAULT 'public', hide_title BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS resources (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, title VARCHAR(180) NOT NULL, category VARCHAR(60) NOT NULL,
 type VARCHAR(60) DEFAULT 'resource', description TEXT NOT NULL, location VARCHAR(120) DEFAULT '', price DECIMAL(12,2) DEFAULT 0, unit VARCHAR(40) DEFAULT '次', tags JSON,
 image VARCHAR(1000) DEFAULT '', visibility ENUM('public','contacts','second_degree') DEFAULT 'public', status ENUM('pending','approved','rejected','archived') DEFAULT 'pending', review_note TEXT, demo BOOLEAN DEFAULT FALSE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(status,category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS demands (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, title VARCHAR(180) NOT NULL, category VARCHAR(60) NOT NULL, description TEXT NOT NULL,
 budget DECIMAL(12,2) DEFAULT 0, location VARCHAR(120) DEFAULT '', visibility ENUM('public','contacts','second_degree') DEFAULT 'public', status ENUM('open','closed','pending','rejected') DEFAULT 'open', demo BOOLEAN DEFAULT FALSE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS favorites (
 user_id INT UNSIGNED NOT NULL, resource_id INT UNSIGNED NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,resource_id), FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(resource_id) REFERENCES resources(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS matches (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, requester_id INT UNSIGNED NOT NULL, owner_id INT UNSIGNED NOT NULL, resource_id INT UNSIGNED NULL, demand_id INT UNSIGNED NULL,
 message TEXT, status ENUM('pending','accepted','completed','rejected','cancelled') DEFAULT 'pending', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(requester_id) REFERENCES users(id), FOREIGN KEY(owner_id) REFERENCES users(id), FOREIGN KEY(resource_id) REFERENCES resources(id), FOREIGN KEY(demand_id) REFERENCES demands(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS contacts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, requester_id INT UNSIGNED NOT NULL, recipient_id INT UNSIGNED NOT NULL, message TEXT,
 status ENUM('pending','accepted','rejected') DEFAULT 'pending', starred_by JSON, hidden_by JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(requester_id) REFERENCES users(id), FOREIGN KEY(recipient_id) REFERENCES users(id), UNIQUE KEY contact_pair(requester_id,recipient_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS introductions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, requester_id INT UNSIGNED NOT NULL, connector_id INT UNSIGNED NOT NULL, target_id INT UNSIGNED NOT NULL, message TEXT,
 status ENUM('pending','accepted','rejected') DEFAULT 'pending', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(requester_id) REFERENCES users(id), FOREIGN KEY(connector_id) REFERENCES users(id), FOREIGN KEY(target_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS messages (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sender_id INT UNSIGNED NOT NULL, recipient_id INT UNSIGNED NOT NULL, content TEXT NOT NULL, read_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(sender_id) REFERENCES users(id), FOREIGN KEY(recipient_id) REFERENCES users(id), INDEX(sender_id,recipient_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notifications (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, title VARCHAR(180) NOT NULL, content TEXT, link VARCHAR(255) DEFAULT '', read_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS leads (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, phone VARCHAR(80) NOT NULL, company VARCHAR(160) DEFAULT '', message TEXT,
 status ENUM('new','contacted','closed') DEFAULT 'new', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ai_models (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, base_url VARCHAR(500) NOT NULL, model VARCHAR(160) NOT NULL, api_key TEXT NOT NULL,
 enabled BOOLEAN DEFAULT TRUE, is_default BOOLEAN DEFAULT FALSE, last_test_status VARCHAR(30) DEFAULT 'untested', last_test_message TEXT,
 last_test_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ai_conversations (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, title VARCHAR(120) NOT NULL, action VARCHAR(30) DEFAULT 'chat', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ai_messages (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, conversation_id INT UNSIGNED NOT NULL, role VARCHAR(20) NOT NULL, content MEDIUMTEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(conversation_id) REFERENCES ai_conversations(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ai_logs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL, model_id INT UNSIGNED NULL, action VARCHAR(40) NOT NULL, status VARCHAR(30) NOT NULL,
 duration_ms INT DEFAULT 0, prompt_tokens INT DEFAULT 0, completion_tokens INT DEFAULT 0, error TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ai_daily_usage (
 user_id INT UNSIGNED NOT NULL, usage_day DATE NOT NULL, calls INT UNSIGNED DEFAULT 0, PRIMARY KEY(user_id,usage_day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(100) PRIMARY KEY, setting_value JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS posts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id INT UNSIGNED NOT NULL,title VARCHAR(180) NOT NULL,content TEXT NOT NULL,
 type ENUM('resource','demand','insight') DEFAULT 'insight',visibility ENUM('public','contacts','second_degree') DEFAULT 'public',industry VARCHAR(100) DEFAULT '',
 status ENUM('published','hidden','closed') DEFAULT 'published',demo BOOLEAN DEFAULT FALSE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),INDEX(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS post_likes (
 post_id INT UNSIGNED NOT NULL,user_id INT UNSIGNED NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(post_id,user_id),FOREIGN KEY(post_id) REFERENCES posts(id),FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS post_comments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,post_id INT UNSIGNED NOT NULL,user_id INT UNSIGNED NOT NULL,content TEXT NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(post_id) REFERENCES posts(id),FOREIGN KEY(user_id) REFERENCES users(id),INDEX(post_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
